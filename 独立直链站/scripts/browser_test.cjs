const {chromium} = require('D:/Tools/Node/node_modules/playwright');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const access=JSON.parse(fs.readFileSync(path.join(root,'test-results/local-access.json'),'utf8'));
const base=process.env.DL_TEST_BASE||'http://127.0.0.1:8780';
const run=Date.now();const initialName=`browser-upload-${run}.zip`, replacementName=`browser-replaced-${run}.exe`;
(async()=>{
 const browser=await chromium.launch({headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1050}});
 const page=await context.newPage(), errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'/manage/login/');
 await page.getByLabel('账号',{exact:true}).fill(access.username);
 await page.getByLabel('密码',{exact:true}).fill(access.password);
 await Promise.all([page.waitForURL('**/manage/'),page.getByRole('button',{name:'登录',exact:true}).click()]);
 assert.equal(await page.locator('tr[data-id]').count(),10);
 await page.screenshot({path:path.join(root,'test-results/desktop-1440.png'),fullPage:true});
 await page.selectOption('#page-size','20');await page.waitForURL('**/manage/**size=20');
 assert.equal(await page.locator('tr[data-id]').count(),20);
 await page.getByRole('link',{name:'下一页',exact:true}).click();
 const visible=await page.locator('tr[data-id]').count();
 assert.equal(await page.locator('.blank-row').count(),20-visible);
 await page.getByRole('button',{name:'新建软件',exact:true}).click();
 await page.locator('#upload-file').setInputFiles({name:initialName,mimeType:'application/zip',buffer:Buffer.from('actual browser upload bytes')});
 await page.locator('#start-upload').click();
 await page.waitForURL(base+'/manage/');
 await page.waitForSelector('tr[data-id]');
 const row=page.locator('tr[data-id]').filter({hasText:initialName}).first();
 await row.waitFor();const id=await row.getAttribute('data-id');
 const fixed=`${base}/d/${id}/`;
 const first=await context.request.get(fixed);assert.equal((await first.body()).toString(),'actual browser upload bytes');
 await row.getByRole('button',{name:'更新',exact:true}).click();
 assert.equal(await page.locator('#name-field').isVisible(),false);
 await page.locator('#upload-file').setInputFiles({name:replacementName,mimeType:'application/octet-stream',buffer:Buffer.from('replacement bytes')});
 await page.locator('#start-upload').click();await page.waitForURL(base+'/manage/');
 await page.locator(`tr[data-id="${id}"]`).filter({hasText:replacementName}).waitFor();
 assert.equal((await (await context.request.get(fixed)).body()).toString(),'replacement bytes');
 const current=page.locator(`tr[data-id="${id}"]`);
 await current.getByRole('button',{name:replacementName,exact:true}).click();
 await page.getByRole('heading',{name:'文件信息',exact:true}).waitFor();
 await page.screenshot({path:path.join(root,'test-results/file-information.png'),fullPage:true});
 await page.locator('#info-dialog').getByRole('button',{name:'完成',exact:true}).click();
 await current.locator('.row-check').check();
 await page.locator('[data-bulk=pause]').click();
 // Drop a real successful response, then retry the original operation.
 let dropped=false;
 await context.route('**/manage/api/actions/',async route=>{
   if(!dropped){dropped=true;await route.fetch();await route.abort();}else await route.continue();
 });
 await page.locator('#action-submit').click();
 await page.locator('#action-error:not([hidden])').waitFor();
 await page.locator('#action-submit').click();
 await page.waitForURL(base+'/manage/');
 await page.locator(`tr[data-id="${id}"] .paused`).waitFor();
 assert.equal((await context.request.get(fixed)).status(),404);
 await context.unroute('**/manage/api/actions/');
 await page.locator(`tr[data-id="${id}"] [data-action=resume]`).click();
 await Promise.all([page.waitForNavigation({waitUntil:'networkidle'}),page.locator('#action-submit').click()]);
 await page.locator(`tr[data-id="${id}"]`).waitFor();
 const checks=[];
 for(const width of [1440,900,390,320]){
   await page.setViewportSize({width,height:1000});await page.goto(base+'/manage/');
   const layout=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,checks:document.querySelectorAll('.row-check').length}));
   assert(layout.scroll<=width,JSON.stringify(layout));
   await page.screenshot({path:path.join(root,`test-results/list-${width}.png`),fullPage:true});
   await page.getByRole('button',{name:'新建软件',exact:true}).click();
   assert(await page.locator('#upload-dialog').isVisible());
   const dialog=await page.locator('#upload-dialog').boundingBox();assert(dialog.x>=0 && dialog.x+dialog.width<=width+1);
   await page.waitForTimeout(220);
   await page.screenshot({path:path.join(root,`test-results/upload-${width}.png`),fullPage:true});
   await page.getByRole('button',{name:'取消',exact:true}).click();
   checks.push(layout);
 }
 await page.goto(base+'/manage/settings/');
 assert.equal(await page.getByRole('heading',{name:'修改密码',exact:true}).count(),1);
 await page.screenshot({path:path.join(root,'test-results/settings-mobile.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 fs.writeFileSync(path.join(root,'test-results/browser-result.json'),JSON.stringify({passed:true,real_upload_replace_fixed_link:true,lost_response_retry:true,layouts:checks,errors},null,2));
 await browser.close();console.log('BROWSER_PASS');
})().catch(e=>{console.error(e);process.exit(1)});
